import { DOCUMENT } from '@angular/common';
import { Component, Inject, OnInit } from '@angular/core';
import { toSignal } from '@angular/core/rxjs-interop';
import { FormBuilder, FormGroup, Validators ,AbstractControl, ValidationErrors} from '@angular/forms';
import { CATEGORY_BUSINESS_TOKEN, ICategoryBusiness } from 'src/app/domain/business-contracts/category-business.contract';
import { COURSE_BUSINESS_TOKEN, ICourseBusiness } from 'src/app/domain/business-contracts/course-business.contract';
import { Course } from 'src/app/domain/entities/course.entity';
import { UserRole } from 'src/app/domain/enums/user-role.enum';

import { USER_BUSINESS_TOKEN, IUserBusiness } from 'src/app/domain/business-contracts/user-business.contract';
import { CreateUserPayload } from 'src/app/domain/entities/user.entity';
import { ToastService } from 'src/app/shared/services/toast-service';
import { Router } from '@angular/router';
import noWhitespaceValidator from 'src/app/shared/validators/no-whitespace.validator';

@Component({
  selector: 'app-add-user',
  templateUrl: './add-user.component.html',
  styleUrls: ['./add-user.component.scss'],
  standalone:false
})
export class AddUserComponent implements OnInit {
  submitted = false;
  isLoading = false;
  addUserForm!: FormGroup;
  roles = [
    { label: 'Teacher', value: UserRole.Teacher },
  ];
  courses: Course[] = [];
  generatedPassword = '';
  showPassword = true;
  categories = toSignal(this.CategoryBusiness.getAllCategories(), { initialValue: [] });

  constructor(
    private fb: FormBuilder,
    @Inject(COURSE_BUSINESS_TOKEN) private readonly courseBusiness: ICourseBusiness,
    @Inject(DOCUMENT) private readonly document: Document,
    @Inject(CATEGORY_BUSINESS_TOKEN) private readonly CategoryBusiness: ICategoryBusiness,
    @Inject(USER_BUSINESS_TOKEN) private readonly userBusiness: IUserBusiness,
    private toastservice:ToastService,
    private router:Router
  ) {
    this.addUserForm = this.fb.group({
      fullName: ['', [ Validators.required,
      noWhitespaceValidator,
      Validators.minLength(3),
      Validators.maxLength(100),
     Validators.pattern(/^[a-zA-Z\u0600-\u06FF]+(?: [a-zA-Z\u0600-\u06FF]+)*$/)]],
      email: ['', [Validators.required, Validators.email, this.emailValidator]],
      role: [null, Validators.required],
      useAutoGeneratedPassword: [true],
      password: [''],
      assignedCategories: [[], Validators.required],
      canCreateExams: [false]
    });

    this.generatedPassword = this.generatePassword(12);
  }

  ngOnInit(): void {
    this.courseBusiness.getAll().subscribe({
      next: courses => {
        this.courses = courses ?? [];
      }
    });

    this.updatePasswordValidators();
    this.addUserForm.get('useAutoGeneratedPassword')?.valueChanges.subscribe(() => {
      this.updatePasswordValidators();
    });
  }

  get f() {
    return this.addUserForm.controls;
  }

  get currentDirection(): string {
    return this.document?.dir || 'ltr';
  }

  get isTeacherRole(): boolean {
    return this.f['role'].value === UserRole.Teacher;
  }

  updatePasswordValidators(): void {
    const passwordControl = this.f['password'];
  const passwordPattern =
    /^(?=.*\d)(?=.*[A-Z])(?=.*[a-z])(?=.*[!@#$%^&*()_+\-=\[\]{}|;:,.<>?/~`]).{8,}$/;
    if (this.f['useAutoGeneratedPassword'].value) {
      passwordControl.clearValidators();
      passwordControl.setValue(this.generatedPassword, { emitEvent: false });
    } else {
      passwordControl.setValidators([Validators.required, Validators.minLength(8),Validators.pattern(passwordPattern)]);
      passwordControl.setValue('', { emitEvent: false });
    }

    passwordControl.updateValueAndValidity();
  }

  switchToManualPassword(): void {
    this.addUserForm.patchValue({ useAutoGeneratedPassword: false });
  }

  regeneratePassword(): void {
    this.generatedPassword = this.generatePassword(12);
    this.addUserForm.patchValue({ password: this.generatedPassword, useAutoGeneratedPassword: true });
  }

generatePassword(length = 12): string {
  const uppercase = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
  const lowercase = 'abcdefghijklmnopqrstuvwxyz';
  const numbers = '0123456789';
  const special = '!@#$%^&*()_+-=[]{}|;:,.<>?/~`';

  const all = uppercase + lowercase + numbers + special;

  // Guarantee one character from each required category
  const passwordChars = [
    uppercase[Math.floor(Math.random() * uppercase.length)],
    lowercase[Math.floor(Math.random() * lowercase.length)],
    numbers[Math.floor(Math.random() * numbers.length)],
    special[Math.floor(Math.random() * special.length)]
  ];

  // Fill the remaining characters randomly
  for (let i = passwordChars.length; i < length; i++) {
    passwordChars.push(
      all[Math.floor(Math.random() * all.length)]
    );
  }

  // Shuffle the password so the required characters aren't always first
  return passwordChars
    .sort(() => Math.random() - 0.5)
    .join('');
}
  onSubmit() {
    this.submitted = true;

    if (this.addUserForm.invalid || this.isLoading) {
      return;
    }

    const payload: CreateUserPayload = {
      fullName: this.f['fullName'].value,
      email: this.f['email'].value,
      role: this.f['role'].value,
      password: this.f['useAutoGeneratedPassword'].value
        ? this.generatedPassword
        : this.f['password'].value,
      assignedCategories: this.isTeacherRole ? this.f['assignedCategories'].value : [],
      canCreateExams: this.isTeacherRole ? this.f['canCreateExams'].value : false
    };

    this.isLoading = true;
    this.userBusiness.createUser(payload).subscribe({
      next: (res) => {
        this.isLoading = false;
        this.router.navigate(['/users']);
      },
      error: (err) => {
        this.isLoading = false;
       this.toastservice.showError(err)
      }
    });
  }
    emailValidator(control: AbstractControl): ValidationErrors | null {
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    const valid = emailRegex.test(control.value);
    return valid ? null : { email: true };
  }
}
